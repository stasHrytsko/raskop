//  МОДЕЛЬ (Фаза 1, tasks.md — Эпики A/B/C/D):
//  Уровень = гробница из нескольких ПОСЛЕДОВАТЕЛЬНЫХ комнат (ROOMS_PER_TIER по тиру).
//  Комната = ROOM_SIZE × ROOM_SIZE, TRAPS_PER_ROOM ловушек, остальные клетки — золото.
//  Первый тап в КАЖДОЙ комнате — честный старт (FIRST_TAP_BLANK): 0 ловушек рядом.
//  Подсказки 1..MAX_CLUE (иначе реген клетки/комнаты).
//  Золото идёт в прогресс квоты сразу за тап — без рюкзака и множителя (тот вернётся
//  только как эффект артефакта «Идол жадности», Эпик H, Фаза 3).
//  Провал (ловушка ИЛИ комната кончилась, а квота не набрана) = вся гробница уровня
//  перегенерируется заново, без лимита попыток. Прогресс кампании (пройденные уровни)
//  при этом не откатывается.
// ───────────────────────────────────────────────
const ROOM_SIZE = 5;           // комната ROOM_SIZE × ROOM_SIZE
const TRAPS_PER_ROOM = 5;      // ловушек в одной комнате

const LEVELS_COUNT = 9;        // уровней в кампании (интерим до таблицы Эпика L — 100)

const FIRST_TAP_BLANK = true;  // первый тап в комнате — 0 ловушек среди соседей
const MAX_CLUE = 5;            // цифры на поле только 1..5 (иначе реген клетки)

// Число комнат на уровень по тиру сложности (интерим-схема до Эпика L)
const ROOMS_PER_TIER = { easy: 2, med: 3, hard: 4 };

// Квота = доля от суммарного золота гробницы (безопасные клетки всех её комнат).
// Плейсхолдер до Монте-Карло тюнинга (Эпик N, Фаза 6).
const QUOTA_RATIO = 0.6;

const PROGRESS_KEY = 'raskop_progress';   // ключ прогресса кампании в localStorage

// Тир сложности и число комнат уровня n (0-индекс)
const tierFor  = n => n < 3 ? 'easy' : n < 6 ? 'med' : 'hard';
const roomsFor = n => ROOMS_PER_TIER[tierFor(n)];

// Квота уровня n: 0.6 от суммарного золота всех его комнат
const safeCellsPerRoom = ROOM_SIZE * ROOM_SIZE - TRAPS_PER_ROOM;
const quotaFor = n => Math.round(QUOTA_RATIO * roomsFor(n) * safeCellsPerRoom);

// ─── Фаза 2 (Эпик E): ключ + закрытая комната-«карман» ───
// Ключ спрятан под случайной безопасной клеткой в комнате до последней (см.
// gen/room.js: placeKey) — игрок заранее не знает, есть ли в комнате ключ. Комната-
// сокровищница всегда последняя в гробнице, без ловушек (чистый бонус, риск в
// сокровищнице — вне скоупа Фазы 2).
const VAULT_SIZE = 3;             // размер бонусной комнаты (VAULT_SIZE × VAULT_SIZE, 0 ловушек)

// ─── Фаза 3 (Эпик G/H): кошелёк + постоянные артефакты ───
const WALLET_KEY = 'raskop_wallet';    // ключ кошелька в localStorage (отдельно от прогресса)
const REPLAY_GOLD_RATIO = 0.2;         // доля золота при повторном прохождении уровня
const SEAL_GOLD_LOSS_RATIO = 0.5;      // доля золота, теряемая при срабатывании Печати хранителя

