// R.gold — он же прогресс квоты (никакого отдельного «рюкзака» в базовом цикле)
function addGold(R, amount){ R.gold += amount; }

function quotaMet(R){ return R.gold >= R.quota; }

// Единая точка расхода золота: уменьшает прогресс квоты (см. Эпик B, tasks.md) —
// выход может закрыться повторно, если он уже был открыт
function spendGold(R, amount){ R.gold = Math.max(0, R.gold - amount); }
